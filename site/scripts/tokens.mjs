// The app's colours, for the site: copies the light and dark CSS variables out of mobile/global.css (Tailwind 3,
// which Tailwind 4 can't import) and maps each to a Tailwind colour, so a change in the app reaches the site.
import fs from 'node:fs';

const css = fs.readFileSync(new URL('../../mobile/global.css', import.meta.url), 'utf8');
const block = sel => { const i = css.indexOf(`${sel} {`); return i < 0 ? '' : css.slice(css.indexOf('{', i) + 1, css.indexOf('}', i)); };
const light = block(':root'), dark = block('.dark:root');
if (!light || !dark) throw new Error('tokens: :root / .dark:root not found in mobile/global.css');
const names = [...light.matchAll(/--([\w-]+):/g)].map(m => m[1]).filter(n => n !== 'radius');
fs.writeFileSync(new URL('../app/tokens.css', import.meta.url), `/* generated by scripts/tokens.mjs from mobile/global.css */
:root {${light}}
.dark {${dark}}
@theme inline {
${names.map(n => `  --color-${n}: hsl(var(--${n}));`).join('\n')}
  --radius-lg: var(--radius);
  --radius-xl: calc(var(--radius) + 4px);
  --radius-md: calc(var(--radius) - 4px);
}
`);
console.log(`tokens: ${names.length} colours`);
